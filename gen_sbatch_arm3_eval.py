"""Write the arm-3 test-evaluation SLURM scripts (ARM3_EVAL_PLAN.md §6). Re-run this rather
than hand-editing the outputs:  python gen_sbatch_arm3_eval.py <dir>

  arm3_eval_a.sbatch   plain s643, then plain s644: eval -> aggregate -> compare vs arm1_vit_b, arm2_r4
  arm3_eval_b.sbatch   plain s645, then box s643 (box also vs plain s643)
  arm3_compare.sbatch  seed_summary.py: the 3 plain seeds vs arm1_vit_b and vs arm2_r4

A failing evaluation or aggregation stops the script. A failing comparison is reported, the
script carries on to the next run (its results are valid on their own), and the script then
ends with exit code 5, so it cannot go unnoticed. Separate generator: no existing file changes.
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"
EVAL_TIME = "06:00:00"
RUNS = {"arm3_eval_a.sbatch": ("arm3_ea", (("plain", 643), ("plain", 644))),
        "arm3_eval_b.sbatch": ("arm3_eb", (("plain", 645), ("box", 643)))}
REFS = (("arm1_vit_b", "SAM ViT-B (arm 1b)"), ("arm2_r4", "Arm 2 r=4 (fine-tuned teacher)"))

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node=8
#SBATCH --gres=gpu:1
#SBATCH --partition=a40
#SBATCH --qos=a40
#SBATCH --account=vihaan
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch_arm3_eval.py -- edit the generator, not this file. (DECISIONS.md D53)
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to any job that writes the same files: {conflicts}.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *A40*) ;;
    *) echo "REFUSING TO START -- this job must run on an A40 (as every evaluation), got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
[ -f "$SEG/data/processed/manifest.csv" ] || {{ echo "manifest not found"; exit 2; }}
"$PY" -c "import torch,surface_distance,numpy;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
CMP_FAIL=0
"""


def names(*jobs: str) -> str:
    return " || ".join(f'$2 == "{j}"' for j in jobs)


def label(variant: str, seed: int) -> str:
    return (f"Arm 3 (plain, seed {seed}): student from scratch, no prompt" if variant == "plain"
            else f"Arm 3 (box, seed {seed}): student from scratch, box input")


def compare(a_dir: str, a_label: str, b_dir: str, b_label: str) -> str:
    return (f'if [ -f "{a_dir}/run.json" ]; then\n'
            f'    "$PY" "$SEG/scripts/compare_arms.py" --a "{a_dir}" --b "{b_dir}" \\\n'
            f'        --label-a "{a_label}" --label-b "{b_label}"\n'
            f'    C=$?; echo "=== compare vs $(basename "{a_dir}") exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n'
            f'else\n'
            f'    echo "=== compare vs $(basename "{a_dir}") skipped: {a_dir}/run.json not found"\n'
            f'fi\n')


def one_run(k: int, variant: str, seed: int) -> str:
    name = f"arm3_{variant}_s{seed}"
    run, out = f"$SEG/runs/{name}", f"$SEG/outputs/{name}"
    lab = label(variant, seed)
    s = (f'echo; echo "=== run {k}: {variant} seed {seed}"\n'
         f'"$PY" "$SEG/scripts/eval_student.py" --processed "$SEG/data/processed" --run-dir "{run}" \\\n'
         f'    --out "{out}" --expect-gpu A40 --resume\n'
         f'RC=$?; echo "=== eval exit $RC"\n'
         f'[ "$RC" -ne 0 ] && {{ echo "STOPPING -- evaluation of {name} failed"; exit "$RC"; }}\n'
         f'"$PY" "$SEG/scripts/aggregate_arm.py" --arm-dir "{out}" --label "{lab}"\n'
         f'RC=$?; echo "=== aggregate exit $RC"\n'
         f'[ "$RC" -ne 0 ] && {{ echo "STOPPING -- aggregation of {name} failed"; exit "$RC"; }}\n')
    for ref, ref_label in REFS:
        s += compare(f"$SEG/outputs/{ref}", ref_label, out, lab)
    return s


for script, (job, runs) in RUNS.items():
    body = "".join(one_run(k, v, s) for k, (v, s) in enumerate(runs, 1))
    body += ('echo\nif [ "$CMP_FAIL" -ne 0 ]; then echo "=== DONE, but a comparison FAILED (see above)"; exit 5; fi\n'
             'echo "=== DONE: both runs evaluated, aggregated and compared"\nexit 0\n')
    doc = ("# Arm 3 TEST EVALUATION (DECISIONS.md D53; ARM3_EVAL_PLAN.md), two runs back to back:\n"
           + "".join(f"#   ({k}) {v} seed {s} -> outputs/arm3_{v}_s{s}\n" for k, (v, s) in enumerate(runs, 1))
           + f"#\n#   sbatch {script}\n#\n# Each run: eval_student.py (resumable) -> aggregate_arm.py -> compare_arms.py vs\n"
           "# arm1_vit_b and arm2_r4. Resubmit after a timeout: finished\n"
           "# evaluations are re-verified and kept.\n")
    (out_dir / script).write_text(
        HEADER.format(job=job, mem="96G", time=EVAL_TIME, seg=SEG, log=script[:-len(".sbatch")]) + doc
        + COMMON.format(seg=SEG, job=job, awk_cond=names(job, "arm3_ta", "arm3_tb"),
                        conflicts="another copy of this script, or arm-3 training")
        + body)

plain = " ".join(f'"$SEG/outputs/arm3_plain_s{s}"' for s in (643, 644, 645))
body = ""
for ref, ref_label in REFS:
    body += (f'echo; echo "=== seed summary vs {ref}"\n'
             f'if [ -f "$SEG/outputs/{ref}/run.json" ]; then\n'
             f'    "$PY" "$SEG/scripts/seed_summary.py" --runs {plain} --ref "$SEG/outputs/{ref}" \\\n'
             f'        --label-ref "{ref_label}" --out "$SEG/outputs/arm3_seeds"\n'
             f'    C=$?; echo "=== summary vs {ref} exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n'
             f'else\n'
             f'    echo "=== summary vs {ref} skipped: run.json not found"; CMP_FAIL=1\n'
             f'fi\n')
# the D8 gap on the same seed: box s643 vs plain s643 (both evaluated by now)
lab_plain, lab_box = label("plain", 643), label("box", 643)     # no nested quotes: Python 3.11
body += ('echo; echo "=== box s643 vs plain s643 (same seed)"\n'
         'if [ -f "$SEG/outputs/arm3_box_s643/run.json" ] && [ -f "$SEG/outputs/arm3_plain_s643/run.json" ]; then\n'
         '    "$PY" "$SEG/scripts/compare_arms.py" --a "$SEG/outputs/arm3_plain_s643" --b "$SEG/outputs/arm3_box_s643" \\\n'
         f'        --label-a "{lab_plain}" --label-b "{lab_box}"\n'
         '    C=$?; echo "=== box vs plain exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n'
         'else\n'
         '    echo "=== box vs plain skipped: an evaluation is missing"; CMP_FAIL=1\n'
         'fi\n')
body += 'echo\n[ "$CMP_FAIL" -ne 0 ] && { echo "=== a summary or comparison FAILED or was skipped"; exit 5; }\necho "=== DONE"\nexit 0\n'
(out_dir / "arm3_compare.sbatch").write_text(
    HEADER.format(job="arm3_cmp", mem="32G", time="00:30:00", seg=SEG, log="arm3_compare")
    + "# Arm 3 SEED SUMMARY (D53): the three plain seeds vs arm 1b and vs arm 2 r4; then the\n"
      "# box student vs the plain student of the same seed (643), the D8 gap.\n#\n"
      "#   sbatch arm3_compare.sbatch     (after both arm3_eval scripts end DONE)\n#\n"
    + COMMON.format(seg=SEG, job="arm3_cmp", awk_cond=names("arm3_ea", "arm3_eb", "arm3_cmp"),
                    conflicts="an arm-3 evaluation, or another copy")
    + body)
print("wrote", sorted(p.name for p in out_dir.glob("arm3_eval_*.sbatch")) + ["arm3_compare.sbatch"])
