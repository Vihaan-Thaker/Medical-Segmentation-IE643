"""Write the arm-3 SLURM scripts (ARM3_CODE_PLAN.md §5). Re-run this rather than hand-editing
the outputs:  python gen_sbatch_arm3.py <dir>

  arm3_preflight.sbatch   one-off checks + timing             -> runs/arm3_preflight
  arm3_train_a.sbatch     plain seed 643, then plain seed 644  -> runs/arm3_plain_s643, _s644
  arm3_train_b.sbatch     plain seed 645, then box seed 643    -> runs/arm3_plain_s645, arm3_box_s643

Separate from gen_sbatch.py on purpose: arm 3 changes no existing file (plan invariant 1).
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"

# The single place these are set (plan §5). Set ARM3_TRAIN_TIME from the preflight's
# recommendation, regenerate, re-run test_student.py, upload.
ARM3_TRAIN_TIME = "16:00:00"
ARM3_WORKERS = 12
ARM3_BATCH = 12
ARM3_EPOCHS = 100
ARM3_STEPS = 1000
# script -> its two runs, in order: (variant, seed)
RUNS = {"arm3_train_a.sbatch": (("plain", 643), ("plain", 644)),
        "arm3_train_b.sbatch": (("plain", 645), ("box", 643))}
JOBS = {"arm3_preflight.sbatch": "arm3_pre", "arm3_train_a.sbatch": "arm3_ta", "arm3_train_b.sbatch": "arm3_tb"}

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node=16
#SBATCH --gres=gpu:1
#SBATCH --partition=dgx
#SBATCH --qos=dgx
#SBATCH --account=vihaan
#SBATCH --mem=128G
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch_arm3.py -- edit the generator, not this file. (DECISIONS.md D42)
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to any other job that writes the same files: {conflicts}.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *A100*) ;;
    *) echo "REFUSING TO START -- this job must run on an A100, got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
[ -f "$SEG/data/processed/manifest.csv" ] || {{ echo "manifest not found: $SEG/data/processed/manifest.csv"; exit 2; }}
"$PY" -c "import torch,surface_distance,numpy;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"""


def names(*jobs: str) -> str:
    return " || ".join(f'$2 == "{j}"' for j in jobs)


def command(variant: str, seed: int, run_dir: str, extra: str = "") -> str:
    return ('"$PY" "$SEG/scripts/train_student.py" --processed "$SEG/data/processed" \\\n'
            f'    --variant {variant} --seed {seed} --run-dir "{run_dir}" \\\n'
            f'    --epochs {ARM3_EPOCHS} --steps-per-epoch {ARM3_STEPS} --batch {ARM3_BATCH} --lr 0.01 '
            f'--workers {ARM3_WORKERS} --expect-gpu A100{extra}\n')


def write(name: str, time_: str, log: str, doc: str, cond: tuple, conflicts: str, body: str) -> None:
    job = JOBS[name]
    text = (HEADER.format(job=job, time=time_, seg=SEG, log=log) + doc
            + COMMON.format(seg=SEG, job=job, awk_cond=names(*cond), conflicts=conflicts) + body)
    (out_dir / name).write_text(text)


write("arm3_preflight.sbatch", "02:00:00", "arm3_preflight",
      """# Arm 3 PREFLIGHT (DECISIONS.md D42; ARM3_CODE_PLAN.md §3.6): run once, before both training jobs.
#
#   sbatch arm3_preflight.sbatch
#
# On an A100: data counts and slice sizes, letterbox ceiling, pipeline identity, augmentation
# examples (runs/arm3_preflight/aug_examples_*.png), can-it-learn, 1,000 real steps (plain) and
# 200 (box) with timing -> runs/arm3_preflight/preflight.json. Ends PREFLIGHT_OK. Then set
# ARM3_TRAIN_TIME in gen_sbatch_arm3.py from it and regenerate.
""",
      ("arm3_pre", "arm3_ta", "arm3_tb"), "another preflight, or a training job",
      command("plain", 643, "$SEG/runs/arm3_preflight", " --preflight")
      + 'RC=$?\necho "=== preflight exit $RC"\nexit "$RC"\n')

for name, ((v1, s1), (v2, s2)) in RUNS.items():
    r1, r2 = f"$SEG/runs/arm3_{v1}_s{s1}", f"$SEG/runs/arm3_{v2}_s{s2}"
    write(name, ARM3_TRAIN_TIME, name[:-len(".sbatch")],
          f"""# Arm 3 TRAINING (DECISIONS.md D42; ARM3_CODE_PLAN.md §3.5), two runs back to back:
#   (1) {v1} student, seed {s1} -> runs/arm3_{v1}_s{s1}
#   (2) {v2} student, seed {s2} -> runs/arm3_{v2}_s{s2}
#
#   sbatch {name}
#
# Run 2 starts only if run 1 ends TRAIN_OK. Resubmit the same script after a timeout: a
# finished run prints TRAIN_OK at once, an unfinished one resumes from its last epoch.
""",
          ("arm3_pre", JOBS[name]), "the preflight, or another copy of this script",
          f'echo "=== run 1: {v1} seed {s1}"\n'
          + command(v1, s1, r1)
          + f'RC=$?\necho "=== run 1 ({v1} seed {s1}) exit $RC"\n'
          + '[ "$RC" -ne 0 ] && { echo "STOPPING -- run 1 failed; run 2 not started"; exit "$RC"; }\n\n'
          + f'echo "=== run 2: {v2} seed {s2}"\n'
          + command(v2, s2, r2)
          + f'RC=$?\necho "=== run 2 ({v2} seed {s2}) exit $RC"\nexit "$RC"\n')

print("wrote", sorted(p.name for p in out_dir.glob("arm3_*.sbatch")))
