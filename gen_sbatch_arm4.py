"""Write the arm-4 SLURM scripts. Re-run this rather than hand-editing the outputs:
    python gen_sbatch_arm4.py <dir>

  teacher_maps.sbatch   arm 2's r4 teacher on every boxed AMOS train slice -> teacher/arm2_r4_train

Separate generator (as gen_sbatch_arm3.py): no existing script or generator is changed.
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"
TEACHER_TIME = "02:00:00"

TEXT = """#!/bin/bash
#SBATCH --job-name=teacher_r4
#SBATCH -N 1
#SBATCH --ntasks-per-node=8
#SBATCH --gres=gpu:1
#SBATCH --partition=a40
#SBATCH --qos=a40
#SBATCH --account=vihaan
#SBATCH --mem=64G
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/teacher_maps.%j.out
#SBATCH --error={seg}/outputs/teacher_maps.%j.err
#
# GENERATED by gen_sbatch_arm4.py -- edit the generator, not this file. (DECISIONS.md D46, D48)
#
# Arm 4 TEACHER MAPS: arm 2's selected r=4 checkpoint on every boxed AMOS train slice, through
# arm 2's exact evaluation path (A40, fp32), clean boxes -> teacher/arm2_r4_train
# (per-kidney float16 logits at native size + teacher_manifest.csv + run.json). Resumable:
# resubmit after a timeout. Ends TEACHER_OK.
#
#   sbatch teacher_maps.sbatch
set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
CKPT=$SEG/checkpoints/sam_vit_b_arm2_r4.pth
OUT=$SEG/teacher/arm2_r4_train
echo "=== job ${{SLURM_JOB_ID:-manual}} (teacher_r4) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to another copy of this job (both would write the same files).
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ($2 == "teacher_r4")')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *A40*) ;;
    *) echo "REFUSING TO START -- this job must run on an A40 (as arm 2's evaluation), got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
[ -f "$CKPT" ] || {{ echo "teacher checkpoint not found: $CKPT"; exit 2; }}
[ -f "$SEG/runs/arm2_selection.json" ] || {{ echo "runs/arm2_selection.json not found (run arm2_select.sbatch)"; exit 2; }}
[ -f "$SEG/data/processed/manifest.csv" ] || {{ echo "manifest not found"; exit 2; }}
"$PY" -c "import torch,surface_distance,numpy,segment_anything;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"$PY" "$SEG/scripts/teacher_maps.py" --processed "$SEG/data/processed" --checkpoint "$CKPT" \\
    --runs "$SEG/runs" --out "$OUT" --expect-gpu A40
RC=$?
echo "=== teacher exit $RC"
exit "$RC"
"""

(out_dir / "teacher_maps.sbatch").write_text(TEXT.format(time=TEACHER_TIME, seg=SEG))
print("wrote", sorted(p.name for p in out_dir.glob("teacher_*.sbatch")))
