"""Write the arm-4 TRAINING SLURM scripts (ARM4_CODE_PLAN.md §10). Re-run this rather than
hand-editing the outputs:  python gen_sbatch_arm4_train.py <dir>

  arm4_preflight.sbatch     one-off checks P1-P11 + timing        -> runs/arm4_preflight
  arm4_train_s643.sbatch    distilled plain student, seed 643     -> runs/arm4_plain_s643
  arm4_train_s644.sbatch    distilled plain student, seed 644     -> runs/arm4_plain_s644
  arm4_train_s645.sbatch    distilled plain student, seed 645     -> runs/arm4_plain_s645

One run per script, so the three train in parallel (3 of the 4 dgx slots). A separate
generator: gen_sbatch_arm4.py (teacher_maps.sbatch) and gen_sbatch_arm3.py stay unchanged.
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"

# The single place these are set. Set ARM4_TRAIN_TIME from the preflight's recommendation,
# regenerate, re-run test_arm4.py, upload.
ARM4_TRAIN_TIME = "08:00:00"
ARM4_WORKERS = 12
ARM4_BATCH = 12
ARM4_EPOCHS = 100
ARM4_STEPS = 1000
SEEDS = (643, 644, 645)
KD = {"lambda": "1.0", "temperature": "1.0", "margin": "0.2", "gate": "0.8"}    # D60
TEACHER_DIR = "$SEG/teacher/arm2_r4_train"
JOBS = {"arm4_preflight.sbatch": "arm4_pre", **{f"arm4_train_s{s}.sbatch": f"arm4_t{s}" for s in SEEDS}}

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node=16
#SBATCH --gres=gpu:1
#SBATCH --partition=dgx
#SBATCH --qos=dgx
#SBATCH --account=vihaan
#SBATCH --mem=128G
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch_arm4_train.py -- edit the generator, not this file. (DECISIONS.md D60)
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to any other job that writes the same files: {conflicts}.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *A100*) ;;
    *) echo "REFUSING TO START -- this job must run on an A100, got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
[ -f "$SEG/data/processed/manifest.csv" ] || {{ echo "manifest not found: $SEG/data/processed/manifest.csv"; exit 2; }}
[ -f "{teacher}/run.json" ] || {{ echo "teacher maps not found: {teacher}/run.json (run teacher_maps.sbatch)"; exit 2; }}
[ -f "$SEG/runs/arm3_plain_s{partner}/run.json" ] || {{ echo "arm-3 partner not found: runs/arm3_plain_s{partner}"; exit 2; }}
"$PY" -c "import torch,surface_distance,numpy;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"""


def names(*jobs: str) -> str:
    return " || ".join(f'$2 == "{j}"' for j in jobs)


def command(seed: int, run_dir: str, extra: str = "") -> str:
    return ('"$PY" "$SEG/scripts/train_student.py" --processed "$SEG/data/processed" \\\n'
            f'    --variant plain --seed {seed} --run-dir "{run_dir}" \\\n'
            f'    --epochs {ARM4_EPOCHS} --steps-per-epoch {ARM4_STEPS} --batch {ARM4_BATCH} --lr 0.01 '
            f'--workers {ARM4_WORKERS} --expect-gpu A100 \\\n'
            f'    --kd --teacher-dir "{TEACHER_DIR}" --kd-lambda {KD["lambda"]} '
            f'--kd-temperature {KD["temperature"]} --kd-margin {KD["margin"]} --kd-gate {KD["gate"]}{extra}\n')


def write(name: str, time_: str, doc: str, cond: tuple, conflicts: str, partner: int, body: str) -> None:
    job = JOBS[name]
    text = (HEADER.format(job=job, time=time_, seg=SEG, log=name[:-len(".sbatch")]) + doc
            + COMMON.format(seg=SEG, job=job, awk_cond=names(*cond), conflicts=conflicts,
                            teacher=TEACHER_DIR, partner=partner) + body)
    (out_dir / name).write_text(text)


ALL = tuple(JOBS.values())
write("arm4_preflight.sbatch", "02:00:00",
      """# Arm 4 PREFLIGHT (DECISIONS.md D60; ARM4_CODE_PLAN.md §8): run once, before the training jobs.
#
#   sbatch arm4_preflight.sbatch
#
# On an A100: P1 environment, P2 data vs arm 3, P3 frozen arm-3 identity (subprocess), P4 teacher
# store, P5/P6 teacher-map alignment, P7 pairing with arm 3, P8 runs/arm4_preflight/kd_examples.png,
# P9 softness, P10 1,000 distillation steps (loss ratio, timing), P11 time estimate. Ends
# PREFLIGHT_OK. Then set ARM4_TRAIN_TIME in gen_sbatch_arm4_train.py from it and regenerate.
""",
      ALL, "another preflight, or an arm-4 training job", 643,
      command(643, "$SEG/runs/arm4_preflight", " --preflight")
      + 'RC=$?\necho "=== preflight exit $RC"\nexit "$RC"\n')

for s in SEEDS:
    name = f"arm4_train_s{s}.sbatch"
    write(name, ARM4_TRAIN_TIME,
          f"""# Arm 4 TRAINING (DECISIONS.md D60; ARM4_CODE_PLAN.md §7): the distilled plain student, seed {s}
#   -> runs/arm4_plain_s{s}, paired with runs/arm3_plain_s{s}
#
#   sbatch {name}
#
# Resubmit the same script after a timeout: a finished run prints TRAIN_OK at once, an unfinished
# one resumes from its last epoch. The three seed scripts may run at the same time.
""",
          ("arm4_pre", JOBS[name]), "the arm-4 preflight, or another copy of this script", s,
          f'echo "=== arm 4: plain seed {s} with distillation"\n'
          + command(s, f"$SEG/runs/arm4_plain_s{s}")
          + f'RC=$?\necho "=== arm 4 seed {s} exit $RC"\nexit "$RC"\n')

print("wrote", sorted(p.name for p in out_dir.glob("arm4_*.sbatch")))
