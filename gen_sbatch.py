"""Write the 4 shard scripts + the merge script from ONE template, so they can only differ
where they must (shard index, names). Re-run this rather than hand-editing the outputs."""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"
N = 4

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node=8
#SBATCH --gres=gpu:1
#SBATCH --partition=a40
#SBATCH --qos=a40
#SBATCH --account=vihaan
#SBATCH --mem=96G
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch.py -- edit the generator, not this file. (DECISIONS.md D29)
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
CKPT=$SEG/checkpoints/sam_vit_h_4b8939.pth
OUT=$SEG/outputs/arm1
NUM_SHARDS={n}

echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}
[ -f "$CKPT" ] || {{ echo "checkpoint not found: $CKPT"; exit 2; }}

# Refuse to run next to any other job that writes the same files: {conflicts}.
# Matched by job name; the cancelled array/single jobs were all named arm1_sam.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
"$PY" -c "import torch,surface_distance,numpy;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"""

SHARD_DOC = """# Arm 1, SHARD {k} of {n}. One of four INDEPENDENT jobs -- submit each with plain sbatch,
# in any order; there is no dependency between them.
#
#   sbatch arm1_shard{k}.sbatch
#
# Scores its fixed quarter of the cases not yet complete in outputs/arm1 (balanced by
# slices) and writes ONLY to outputs/arm1/shards/{k}_of_{n}/. The split is frozen in that
# folder's assigned.json on first start. Timed out or crashed? Resubmit the same script:
# it resumes its own files, redoing only a half-written case. Ends with SHARD_OK.
# When all four say SHARD_OK, run arm1_merge.sbatch.
"""

SHARD_RUN = """"$PY" "$SEG/scripts/eval_sam.py" \\
    --processed "$SEG/data/processed" \\
    --checkpoint "$CKPT" \\
    --model-type vit_h \\
    --out "$OUT" \\
    --shard {k} --num-shards "$NUM_SHARDS"
RC=$?
echo "=== shard {k} exit $RC"
exit "$RC"
"""

MERGE_DOC = """# Arm 1, MERGE. Run by hand once all four shard jobs have finished with SHARD_OK:
#
#   sbatch arm1_merge.sbatch
#
# Combines outputs/arm1 (AMOS + CHAOS + 38 WORD from job 336480) with the four shard
# folders into outputs/arm1/{{instances,volumes_3d}}.csv, re-verifies every row and count
# (52,580 instance rows), re-runs ~120 QC kidneys through SAM, then aggregates.
# If any shard is missing or incomplete it fails and CHANGES NOTHING -- resubmit that shard.
# Ends with EVAL_OK and the results table.
"""

MERGE_RUN = """"$PY" "$SEG/scripts/eval_sam.py" \\
    --processed "$SEG/data/processed" \\
    --checkpoint "$CKPT" \\
    --model-type vit_h \\
    --out "$OUT" \\
    --merge "$NUM_SHARDS"
RC=$?
echo "=== merge exit $RC"
[ "$RC" -ne 0 ] && exit "$RC"

echo; echo "=== aggregate"
"$PY" "$SEG/scripts/aggregate_arm.py" --arm-dir "$OUT" \\
    --label "Arm 1: off-the-shelf SAM (vit_h, zero-shot, oracle box prompts)"
ARC=$?
echo "=== aggregate exit $ARC"
exit "$ARC"
"""

for k in range(N):
    job = f"arm1_s{k}"
    # a duplicate of this shard, the merge, or any leftover arm1_sam job
    cond = f'$2 == "{job}" || $2 == "arm1_merge" || $2 == "arm1_sam"'
    text = (HEADER.format(job=job, time="03:00:00", seg=SEG, log=f"arm1_shard{k}")
            + SHARD_DOC.format(k=k, n=N)
            + COMMON.format(seg=SEG, n=N, job=job, awk_cond=cond,
                            conflicts=f"another copy of shard {k}, the merge, or an old arm1_sam job")
            + SHARD_RUN.format(k=k))
    (out_dir / f"arm1_shard{k}.sbatch").write_text(text)

cond = " || ".join(f'$2 == "arm1_s{k}"' for k in range(N)) + ' || $2 == "arm1_merge" || $2 == "arm1_sam"'
text = (HEADER.format(job="arm1_merge", time="01:00:00", seg=SEG, log="arm1_merge")
        + MERGE_DOC
        + COMMON.format(seg=SEG, n=N, job="arm1_merge", awk_cond=cond,
                        conflicts="any shard still queued or running, another merge, or an old arm1_sam job")
        + MERGE_RUN)
(out_dir / "arm1_merge.sbatch").write_text(text)
print("wrote", sorted(p.name for p in out_dir.glob("arm1_*.sbatch")))
