"""Write every arm-1 SLURM script from ONE template, so scripts can only differ where they
must (model, checkpoint, output folder, shard index, names, time limit). Re-run this rather
than hand-editing the outputs:  python gen_sbatch.py <dir>

  ViT-H (D29, already run):  arm1_shard{0..3}.sbatch + arm1_merge.sbatch -> outputs/arm1
  ViT-B (D32):               arm1_vitb.sbatch (primary, one job)          -> outputs/arm1_vit_b
                             fallback: arm1_vitb_shard{0,1}.sbatch + arm1_vitb_merge.sbatch
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"
N = 4          # ViT-H shards
NB = 2         # ViT-B fallback shards

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node=8
#SBATCH --gres=gpu:1
#SBATCH --partition=a40
#SBATCH --qos=a40
#SBATCH --account=vihaan
#SBATCH --mem=96G
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch.py -- edit the generator, not this file. (DECISIONS.md {dref})
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
CKPT=$SEG/checkpoints/{ckpt}
OUT=$SEG/outputs/{out}
{shards_line}
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}
[ -f "$CKPT" ] || {{ echo "checkpoint not found: $CKPT"; exit 2; }}

# Refuse to run next to any other job that writes the same files: {conflicts}.
# Matched by job name; the cancelled array/single jobs were all named arm1_sam.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
"$PY" -c "import torch,surface_distance,numpy;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"""

EVAL = """"$PY" "$SEG/scripts/eval_sam.py" \\
    --processed "$SEG/data/processed" \\
    --checkpoint "$CKPT" \\
    --model-type {model} \\
    --out "$OUT" \\
    {mode_args}
"""

SHARD_TAIL = """RC=$?
echo "=== shard {k} exit $RC"
exit "$RC"
"""

AGG = """RC=$?
echo "=== {what} exit $RC"
[ "$RC" -ne 0 ] && exit "$RC"

echo; echo "=== aggregate"
"$PY" "$SEG/scripts/aggregate_arm.py" --arm-dir "$OUT" \\
    --label "Arm 1: off-the-shelf SAM ({model}, zero-shot, oracle box prompts)"
ARC=$?
echo "=== aggregate exit $ARC"
"""

# ViT-B only: paired comparison against the ViT-H arm 1. Its outcome is reported but does
# not change the job's exit code -- the ViT-B results are valid either way (D32).
COMPARE = """[ "$ARC" -ne 0 ] && exit "$ARC"

REF=$SEG/outputs/arm1
echo; echo "=== compare with SAM ViT-H ($REF)"
if [ -f "$REF/run.json" ]; then
    "$PY" "$SEG/scripts/compare_arms.py" --a "$REF" --b "$OUT" \\
        --label-a "SAM ViT-H" --label-b "SAM ViT-B"
    echo "=== compare exit $? (the ViT-B results above are valid either way)"
else
    echo "=== compare skipped: $REF/run.json not found"
fi
exit "$ARC"
"""

# ------------------------------------------------------------------ ViT-H docs (D29)
SHARD_DOC = """# Arm 1, SHARD {k} of {n}. One of four INDEPENDENT jobs -- submit each with plain sbatch,
# in any order; there is no dependency between them.
#
#   sbatch arm1_shard{k}.sbatch
#
# Scores its fixed quarter of the cases not yet complete in outputs/arm1 (balanced by
# slices) and writes ONLY to outputs/arm1/shards/{k}_of_{n}/. The split is frozen in that
# folder's assigned.json on first start. Timed out or crashed? Resubmit the same script:
# it resumes its own files, redoing only a half-written case. Ends with SHARD_OK.
# When all four say SHARD_OK, run arm1_merge.sbatch.
"""

MERGE_DOC = """# Arm 1, MERGE. Run by hand once all four shard jobs have finished with SHARD_OK:
#
#   sbatch arm1_merge.sbatch
#
# Combines outputs/arm1 (AMOS + CHAOS + 38 WORD from job 336480) with the four shard
# folders into outputs/arm1/{{instances,volumes_3d}}.csv, re-verifies every row and count
# (52,580 instance rows), re-runs ~120 QC kidneys through SAM, then aggregates.
# If any shard is missing or incomplete it fails and CHANGES NOTHING -- resubmit that shard.
# Ends with EVAL_OK and the results table.
"""

# ------------------------------------------------------------------ ViT-B docs (D32)
VITB_DOC = """# Arm 1b: off-the-shelf SAM ViT-B on all 231 test cases, ONE job (DECISIONS.md D32).
#
#   sbatch arm1_vitb.sbatch
#
# Same data, boxes (seeded per kidney, so identical to the ViT-H run), metrics and checks
# as arm 1; only the model differs. Writes ONLY to outputs/arm1_vit_b, stamped as ViT-B
# (model.json), so it can never mix with the ViT-H results in outputs/arm1.
# Always resumes: if it times out or crashes, submit this same script again.
# Ends with EVAL_OK, the results table, then a paired comparison with ViT-H (COMPARE_OK).
# Expected ~30-60 min (unmeasured); the 3 h limit is the margin.
# Fallback ONLY if one job cannot finish: arm1_vitb_shard0/1.sbatch, then arm1_vitb_merge.sbatch.
"""

VITB_SHARD_DOC = """# Arm 1b FALLBACK, SHARD {k} of {n} -- use only if arm1_vitb.sbatch cannot finish in one job.
# The two shards are INDEPENDENT -- submit both with plain sbatch, in any order:
#
#   sbatch arm1_vitb_shard{k}.sbatch
#
# Scores its half of the cases not yet complete in outputs/arm1_vit_b (balanced by slices)
# and writes ONLY to outputs/arm1_vit_b/shards/{k}_of_{n}/. Resubmit the same script to
# resume. Ends with SHARD_OK. When both say SHARD_OK, run arm1_vitb_merge.sbatch.
# Once you switch to the fallback, stay on it (do not resubmit arm1_vitb.sbatch).
"""

VITB_MERGE_DOC = """# Arm 1b FALLBACK, MERGE. Run by hand once both ViT-B shard jobs have finished with SHARD_OK:
#
#   sbatch arm1_vitb_merge.sbatch
#
# Combines outputs/arm1_vit_b with its two shard folders, re-verifies every row and count
# (52,580 instance rows), re-runs ~120 QC kidneys, aggregates, then compares with ViT-H.
# If any shard is missing or incomplete it fails and CHANGES NOTHING -- resubmit that shard.
"""


def write(name: str, text: str) -> None:
    (out_dir / name).write_text(text)


def common(job: str, ckpt: str, out: str, shards_line: str, cond: str, conflicts: str) -> str:
    return COMMON.format(seg=SEG, job=job, ckpt=ckpt, out=out, shards_line=shards_line,
                         awk_cond=cond, conflicts=conflicts)


def names(*jobs: str) -> str:
    return " || ".join(f'$2 == "{j}"' for j in jobs)


# ---------------------------------------------------------------- ViT-H (unchanged)
H_CKPT, H_OUT = "sam_vit_h_4b8939.pth", "arm1"
for k in range(N):
    job = f"arm1_s{k}"
    # a duplicate of this shard, the merge, or any leftover arm1_sam job
    write(f"arm1_shard{k}.sbatch",
          HEADER.format(job=job, time="03:00:00", seg=SEG, log=f"arm1_shard{k}", dref="D29")
          + SHARD_DOC.format(k=k, n=N)
          + common(job, H_CKPT, H_OUT, f"NUM_SHARDS={N}\n", names(job, "arm1_merge", "arm1_sam"),
                   f"another copy of shard {k}, the merge, or an old arm1_sam job")
          + EVAL.format(model="vit_h", mode_args=f'--shard {k} --num-shards "$NUM_SHARDS"')
          + SHARD_TAIL.format(k=k))

write("arm1_merge.sbatch",
      HEADER.format(job="arm1_merge", time="01:00:00", seg=SEG, log="arm1_merge", dref="D29")
      + MERGE_DOC
      + common("arm1_merge", H_CKPT, H_OUT, f"NUM_SHARDS={N}\n",
               names(*[f"arm1_s{k}" for k in range(N)], "arm1_merge", "arm1_sam"),
               "any shard still queued or running, another merge, or an old arm1_sam job")
      + EVAL.format(model="vit_h", mode_args='--merge "$NUM_SHARDS"')
      + AGG.format(what="merge", model="vit_h")
      + 'exit "$ARC"\n')

# ---------------------------------------------------------------- ViT-B (D32)
B_CKPT, B_OUT = "sam_vit_b_01ec64.pth", "arm1_vit_b"
B_JOBS = ("arm1b", *[f"arm1b_s{k}" for k in range(NB)], "arm1b_merge")

write("arm1_vitb.sbatch",
      HEADER.format(job="arm1b", time="03:00:00", seg=SEG, log="arm1_vitb", dref="D32")
      + VITB_DOC
      + common("arm1b", B_CKPT, B_OUT, "", names(*B_JOBS, "arm1_sam"),
               "another copy of this job, a ViT-B fallback shard or merge, or an arm1_sam job")
      + EVAL.format(model="vit_b", mode_args="--resume")
      + AGG.format(what="eval", model="vit_b")
      + COMPARE)

for k in range(NB):
    job = f"arm1b_s{k}"
    write(f"arm1_vitb_shard{k}.sbatch",
          HEADER.format(job=job, time="02:00:00", seg=SEG, log=f"arm1_vitb_shard{k}", dref="D32")
          + VITB_SHARD_DOC.format(k=k, n=NB)
          + common(job, B_CKPT, B_OUT, f"NUM_SHARDS={NB}\n",
                   names("arm1b", job, "arm1b_merge", "arm1_sam"),
                   f"the primary ViT-B job, another copy of shard {k}, the merge, or an arm1_sam job")
          + EVAL.format(model="vit_b", mode_args=f'--shard {k} --num-shards "$NUM_SHARDS"')
          + SHARD_TAIL.format(k=k))

write("arm1_vitb_merge.sbatch",
      HEADER.format(job="arm1b_merge", time="01:00:00", seg=SEG, log="arm1_vitb_merge", dref="D32")
      + VITB_MERGE_DOC
      + common("arm1b_merge", B_CKPT, B_OUT, f"NUM_SHARDS={NB}\n", names(*B_JOBS, "arm1_sam"),
               "the primary ViT-B job, any ViT-B shard, another merge, or an arm1_sam job")
      + EVAL.format(model="vit_b", mode_args='--merge "$NUM_SHARDS"')
      + AGG.format(what="merge", model="vit_b")
      + COMPARE)

# ======================================================================= ARM 2 (D33-D34)
# The ONLY place the two training scripts take batch / accumulation / time from. Set them from
# the preflight's preflight.json ("recommended", "estimate"), regenerate, re-test, upload.
ARM2_BATCH = 8
ARM2_ACCUM = 1
ARM2_GRAD_CKPT = False
ARM2_TRAIN_TIME = "32:00:00"
ARM2_WORKERS = 10
BASE_CKPT = "sam_vit_b_01ec64.pth"

ARM2_HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node={ntasks}
#SBATCH --gres=gpu:1
#SBATCH --partition={part}
#SBATCH --qos={part}
#SBATCH --account=vihaan
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch.py -- edit the generator, not this file. (DECISIONS.md D34)
#
"""

ARM2_COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
{vars}
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to any other job that writes the same files: {conflicts}.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *{gpu}*) ;;
    *) echo "REFUSING TO START -- this job must run on an {gpu}, got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
{file_checks}"$PY" -c "import torch,surface_distance,numpy,segment_anything;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"""

DGX = {"part": "dgx", "ntasks": 16, "mem": "128G", "gpu": "A100"}
A40_EVAL = {"part": "a40", "ntasks": 8, "mem": "96G", "gpu": "A40"}
A40_CPU = {"part": "a40", "ntasks": 8, "mem": "32G", "gpu": "A40"}


def arm2(name, job, time_, log, hw, doc, vars_, checks, cond_jobs, conflicts, body):
    write(name, ARM2_HEADER.format(job=job, ntasks=hw["ntasks"], part=hw["part"], mem=hw["mem"],
                                   time=time_, seg=SEG, log=log)
          + doc
          + ARM2_COMMON.format(seg=SEG, job=job, vars=vars_, file_checks=checks,
                               awk_cond=names(*cond_jobs), conflicts=conflicts, gpu=hw["gpu"])
          + body)


TRAIN_ARGS = ('--processed "$SEG/data/processed" --checkpoint "$CKPT" --rank {r} --alpha 4 \\\n'
              '    --run-dir "$RUN" --merged-out "$MERGED" --epochs 35 --batch {b} --accum {a} \\\n'
              '    --lr-lora 5e-4 --lr-dec 1e-4 --seed 643 --workers {w} --expect-gpu A100{gc}')
gc_flag = " --grad-checkpoint" if ARM2_GRAD_CKPT else ""

arm2("arm2_preflight.sbatch", "arm2_pre", "01:00:00", "arm2_preflight", DGX,
     """# Arm 2 PREFLIGHT (DECISIONS.md D33-D34): run once, before both training jobs.
#
#   sbatch arm2_preflight.sbatch
#
# On an A100: (1) our training forward == SamPredictor on 196 AMOS-val slices, (2) LR sanity
# over 300 real steps (plus the out-of-memory fallback ladder), (3) can-it-learn on 16 slices,
# (4) timing -> runs/arm2_preflight/preflight.json. Ends PREFLIGHT_OK. Then set ARM2_BATCH /
# ARM2_ACCUM / ARM2_TRAIN_TIME in gen_sbatch.py from it and regenerate.
""",
     f'CKPT=$SEG/checkpoints/{BASE_CKPT}\nRUN=$SEG/runs/arm2_preflight\nMERGED=""\n',
     '[ -f "$CKPT" ] || { echo "checkpoint not found: $CKPT"; exit 2; }\n',
     ("arm2_pre", "arm2_r4_tr", "arm2_r8_tr"),
     "another preflight, or a training job",
     '"$PY" "$SEG/scripts/train_sam_lora.py" '
     + TRAIN_ARGS.format(r=4, b=ARM2_BATCH, a=ARM2_ACCUM, w=ARM2_WORKERS, gc=gc_flag)
       .replace(' --merged-out "$MERGED"', '') + ' --preflight\n'
     'RC=$?\necho "=== preflight exit $RC"\nexit "$RC"\n')

for r in (4, 8):
    arm2(f"arm2_r{r}_train.sbatch", f"arm2_r{r}_tr", ARM2_TRAIN_TIME, f"arm2_r{r}_train", DGX,
         f"""# Arm 2 TRAINING, LoRA rank {r} (alpha 4) + full mask decoder, on an A100 (DECISIONS.md D33-D34).
#
#   sbatch arm2_r{r}_train.sbatch
#
# 35 epochs on AMOS train, best epoch by AMOS val; resumable (resubmit the same script after a
# timeout -- it continues from the last completed epoch; a finished run exits TRAIN_OK at once).
# Then merges the best epoch's LoRA into a plain ViT-B checkpoint and checks the merge
# (FINALIZE_OK). The two training scripts differ ONLY in the rank (a test enforces this).
""",
         f'CKPT=$SEG/checkpoints/{BASE_CKPT}\nRUN=$SEG/runs/arm2_r{r}\n'
         f'MERGED=$SEG/checkpoints/sam_vit_b_arm2_r{r}.pth\n',
         '[ -f "$CKPT" ] || { echo "checkpoint not found: $CKPT"; exit 2; }\n',
         (f"arm2_r{r}_tr", f"arm2_r{r}_ev", "arm2_pre"),
         f"another copy of this training job, the r{r} evaluation, or the preflight",
         '"$PY" "$SEG/scripts/train_sam_lora.py" '
         + TRAIN_ARGS.format(r=r, b=ARM2_BATCH, a=ARM2_ACCUM, w=ARM2_WORKERS, gc=gc_flag) + '\n'
         'RC=$?\necho "=== train exit $RC"\n[ "$RC" -ne 0 ] && exit "$RC"\n\n'
         'echo; echo "=== finalize (merge + merge check)"\n'
         '"$PY" "$SEG/scripts/train_sam_lora.py" '
         + TRAIN_ARGS.format(r=r, b=ARM2_BATCH, a=ARM2_ACCUM, w=ARM2_WORKERS, gc=gc_flag)
         + ' --finalize\nFRC=$?\necho "=== finalize exit $FRC"\nexit "$FRC"\n')

arm2("arm2_select.sbatch", "arm2_sel", "00:20:00", "arm2_select", A40_CPU,
     """# Arm 2 RANK SELECTION (DECISIONS.md D33): from AMOS-val results only, BEFORE any arm-2 test.
#
#   sbatch arm2_select.sbatch          (after both training jobs end FINALIZE_OK)
#
# Writes runs/arm2_selection.json; refuses if an outputs/arm2_r* folder already exists or if the
# two runs differ in anything but rank. Ends SELECT_OK.
""",
     "",
     "",
     ("arm2_r4_tr", "arm2_r8_tr", "arm2_r4_ev", "arm2_r8_ev", "arm2_sel"),
     "a training or evaluation job, or another selection",
     '"$PY" "$SEG/scripts/select_rank.py" --runs "$SEG/runs" --outputs "$SEG/outputs"\n'
     'RC=$?\necho "=== select exit $RC"\nexit "$RC"\n')

for r in (4, 8):
    arm2(f"arm2_r{r}_eval.sbatch", f"arm2_r{r}_ev", "03:00:00", f"arm2_r{r}_eval", A40_EVAL,
         f"""# Arm 2 EVALUATION, rank {r}, on an A40 exactly like arms 1 / 1b (DECISIONS.md D33-D34).
#
#   sbatch arm2_r{r}_eval.sbatch       (after arm2_select.sbatch ends SELECT_OK)
#
# Unchanged eval_sam.py on the merged checkpoint -> outputs/arm2_r{r} (stamped with its sha256),
# then aggregation, then a paired comparison with arm 1b (outputs/arm1_vit_b).
# Always resumes: resubmit the same script after a timeout.
""",
         f'CKPT=$SEG/checkpoints/{BASE_CKPT}\nRUN=$SEG/runs/arm2_r{r}\n'
         f'MERGED=$SEG/checkpoints/sam_vit_b_arm2_r{r}.pth\nOUT=$SEG/outputs/arm2_r{r}\n'
         'SEL=$SEG/runs/arm2_selection.json\nREF=$SEG/outputs/arm1_vit_b\n',
         '[ -f "$SEL" ] || { echo "REFUSING TO START -- $SEL missing: run arm2_select.sbatch first"; exit 5; }\n'
         f'"$PY" "$SEG/scripts/train_sam_lora.py" --processed "$SEG/data/processed" --checkpoint "$CKPT" \\\n'
         f'    --rank {r} --run-dir "$RUN" --merged-out "$MERGED" --check-merged || {{ echo "REFUSING TO START -- merged checkpoint not verified"; exit 6; }}\n',
         (f"arm2_r{r}_tr", f"arm2_r{r}_ev", "arm2_sel"),
         f"the r{r} training job, another copy of this evaluation, or the selection",
         '"$PY" "$SEG/scripts/eval_sam.py" \\\n'
         '    --processed "$SEG/data/processed" \\\n'
         '    --checkpoint "$MERGED" \\\n'
         '    --model-type vit_b \\\n'
         '    --out "$OUT" \\\n'
         '    --resume\n'
         'RC=$?\necho "=== eval exit $RC"\n[ "$RC" -ne 0 ] && exit "$RC"\n\n'
         'echo; echo "=== aggregate"\n'
         '"$PY" "$SEG/scripts/aggregate_arm.py" --arm-dir "$OUT" \\\n'
         f'    --label "Arm 2 (r={r}): SAM ViT-B fine-tuned (LoRA q,v r={r} + decoder)"\n'
         'ARC=$?\necho "=== aggregate exit $ARC"\n[ "$ARC" -ne 0 ] && exit "$ARC"\n\n'
         'echo; echo "=== compare with arm 1b, SAM ViT-B off-the-shelf ($REF)"\n'
         'if [ -f "$REF/run.json" ]; then\n'
         '    "$PY" "$SEG/scripts/compare_arms.py" --a "$REF" --b "$OUT" \\\n'
         f'        --label-a "SAM ViT-B (arm 1b)" --label-b "Arm 2 r={r}"\n'
         '    echo "=== compare exit $? (the arm-2 results above are valid either way)"\n'
         'else\n'
         '    echo "=== compare skipped: $REF/run.json not found (run arm1_vitb.sbatch)"\n'
         'fi\nexit "$ARC"\n')

arm2("arm2_compare.sbatch", "arm2_cmp", "00:30:00", "arm2_compare", A40_CPU,
     """# Arm 2 RANK COMPARISON r4 -> r8 on identical prompts (DECISIONS.md D33).
#
#   sbatch arm2_compare.sbatch         (after both arm-2 evaluations end EVAL_OK)
""",
     "A=$SEG/outputs/arm2_r4\nB=$SEG/outputs/arm2_r8\n",
     '[ -f "$A/run.json" ] && [ -f "$B/run.json" ] || { echo "REFUSING TO START -- both arm-2 evaluations must finish first"; exit 5; }\n',
     ("arm2_r4_ev", "arm2_r8_ev", "arm2_cmp"),
     "an arm-2 evaluation, or another comparison",
     '"$PY" "$SEG/scripts/compare_arms.py" --a "$A" --b "$B" --label-a "Arm 2 r=4" --label-b "Arm 2 r=8"\n'
     'RC=$?\necho "=== compare exit $RC"\nexit "$RC"\n')

print("wrote", sorted(p.name for p in out_dir.glob("arm*_*.sbatch")))
