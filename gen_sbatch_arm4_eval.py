"""Write the arm-4 test-evaluation SLURM scripts (ARM4_CODE_PLAN.md §11). Re-run this rather
than hand-editing the outputs:  python gen_sbatch_arm4_eval.py <dir>

  arm4_eval_a.sbatch    s643, then s644: eval -> aggregate -> compare vs arm1_vit_b, arm2_r4 and
                        the same-seed arm-3 student (arm3_plain_s<seed>)
  arm4_eval_b.sbatch    s645, the same steps
  arm4_compare.sbatch   seed_summary.py: the 3 arm-4 seeds vs arm1_vit_b, vs arm2_r4, and
                        seed-paired (--ref-runs) vs the 3 arm-3 seeds -> outputs/arm4_seeds

The arm-3 evaluation template (gen_sbatch_arm3_eval.py, unchanged): a failing evaluation or
aggregation stops the script; a failing comparison is reported, the script carries on and
ends with exit code 5. Same A40 partition as every evaluation.
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"
EVAL_TIME = "06:00:00"
SEEDS = (643, 644, 645)
RUNS = {"arm4_eval_a.sbatch": ("arm4_ea", (643, 644)), "arm4_eval_b.sbatch": ("arm4_eb", (645,))}
TRAIN_JOBS = ("arm4_pre", "arm4_t643", "arm4_t644", "arm4_t645")       # gen_sbatch_arm4_train.JOBS
REFS = (("arm1_vit_b", "SAM ViT-B (arm 1b)"), ("arm2_r4", "Arm 2 r=4 (fine-tuned teacher)"))

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node=8
#SBATCH --gres=gpu:1
#SBATCH --partition=a40
#SBATCH --qos=a40
#SBATCH --account=vihaan
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch_arm4_eval.py -- edit the generator, not this file. (DECISIONS.md D66)
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to any job that writes the same files: {conflicts}.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *A40*) ;;
    *) echo "REFUSING TO START -- this job must run on an A40 (as every evaluation), got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
[ -f "$SEG/data/processed/manifest.csv" ] || {{ echo "manifest not found"; exit 2; }}
"$PY" -c "import torch,surface_distance,numpy;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
CMP_FAIL=0
"""


def names(*jobs: str) -> str:
    return " || ".join(f'$2 == "{j}"' for j in jobs)


def label(seed: int) -> str:
    return f"Arm 4 (plain, seed {seed}): student distilled from arm 2, no prompt"


def arm3_label(seed: int) -> str:
    return f"Arm 3 (plain, seed {seed}): student from scratch, no prompt"


def compare(a_dir: str, a_label: str, b_dir: str, b_label: str) -> str:
    return (f'if [ -f "{a_dir}/run.json" ]; then\n'
            f'    "$PY" "$SEG/scripts/compare_arms.py" --a "{a_dir}" --b "{b_dir}" \\\n'
            f'        --label-a "{a_label}" --label-b "{b_label}"\n'
            f'    C=$?; echo "=== compare vs $(basename "{a_dir}") exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n'
            f'else\n'
            f'    echo "=== compare vs $(basename "{a_dir}") skipped: {a_dir}/run.json not found"; CMP_FAIL=1\n'
            f'fi\n')


def one_run(k: int, seed: int) -> str:
    name = f"arm4_plain_s{seed}"
    run, out = f"$SEG/runs/{name}", f"$SEG/outputs/{name}"
    lab = label(seed)
    s = (f'echo; echo "=== run {k}: arm 4 seed {seed}"\n'
         f'"$PY" "$SEG/scripts/eval_student.py" --processed "$SEG/data/processed" --run-dir "{run}" \\\n'
         f'    --out "{out}" --expect-gpu A40 --resume\n'
         f'RC=$?; echo "=== eval exit $RC"\n'
         f'[ "$RC" -ne 0 ] && {{ echo "STOPPING -- evaluation of {name} failed"; exit "$RC"; }}\n'
         f'"$PY" "$SEG/scripts/aggregate_arm.py" --arm-dir "{out}" --label "{lab}"\n'
         f'RC=$?; echo "=== aggregate exit $RC"\n'
         f'[ "$RC" -ne 0 ] && {{ echo "STOPPING -- aggregation of {name} failed"; exit "$RC"; }}\n')
    for ref, ref_label in REFS + ((f"arm3_plain_s{seed}", arm3_label(seed)),):
        s += compare(f"$SEG/outputs/{ref}", ref_label, out, lab)
    return s


for script, (job, seeds) in RUNS.items():
    body = "".join(one_run(k, s) for k, s in enumerate(seeds, 1))
    body += ('echo\nif [ "$CMP_FAIL" -ne 0 ]; then echo "=== DONE, but a comparison FAILED (see above)"; exit 5; fi\n'
             'echo "=== DONE: evaluated, aggregated and compared"\nexit 0\n')
    doc = ("# Arm 4 TEST EVALUATION (DECISIONS.md D66; ARM4_CODE_PLAN.md §11):\n"
           + "".join(f"#   ({k}) distilled plain student, seed {s} -> outputs/arm4_plain_s{s}\n"
                     for k, s in enumerate(seeds, 1))
           + f"#\n#   sbatch {script}\n#\n# Each run: eval_student.py (resumable) -> aggregate_arm.py -> compare_arms.py vs\n"
           "# arm1_vit_b, arm2_r4 and the same-seed arm-3 student. Resubmit after a timeout: finished\n"
           "# evaluations are re-verified and kept. arm4_eval_a and arm4_eval_b may run together.\n")
    (out_dir / script).write_text(
        HEADER.format(job=job, mem="96G", time=EVAL_TIME, seg=SEG, log=script[:-len(".sbatch")]) + doc
        + COMMON.format(seg=SEG, job=job, awk_cond=names(job, *TRAIN_JOBS),
                        conflicts="another copy of this script, or arm-4 training")
        + body)

runs = " ".join(f'"$SEG/outputs/arm4_plain_s{s}"' for s in SEEDS)
refs3 = " ".join(f'"$SEG/outputs/arm3_plain_s{s}"' for s in SEEDS)
body = ""
for ref, ref_label in REFS:
    body += (f'echo; echo "=== seed summary vs {ref}"\n'
             f'if [ -f "$SEG/outputs/{ref}/run.json" ]; then\n'
             f'    "$PY" "$SEG/scripts/seed_summary.py" --runs {runs} --ref "$SEG/outputs/{ref}" \\\n'
             f'        --label-ref "{ref_label}" --out "$SEG/outputs/arm4_seeds"\n'
             f'    C=$?; echo "=== summary vs {ref} exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n'
             f'else\n'
             f'    echo "=== summary vs {ref} skipped: run.json not found"; CMP_FAIL=1\n'
             f'fi\n')
body += ('echo; echo "=== seed-paired summary vs the 3 arm-3 seeds (the distillation effect)"\n'
         '"$PY" "$SEG/scripts/seed_summary.py" --runs ' + runs + ' --ref-runs ' + refs3 + ' \\\n'
         '    --label-ref "Arm 3 plain student" --out "$SEG/outputs/arm4_seeds"\n'
         'C=$?; echo "=== summary vs arm 3 exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n')
body += 'echo\n[ "$CMP_FAIL" -ne 0 ] && { echo "=== a summary FAILED or was skipped"; exit 5; }\necho "=== DONE"\nexit 0\n'
(out_dir / "arm4_compare.sbatch").write_text(
    HEADER.format(job="arm4_cmp", mem="32G", time="00:30:00", seg=SEG, log="arm4_compare")
    + "# Arm 4 SEED SUMMARY (D66): the three distilled seeds vs arm 1b, vs arm 2 r4, and seed-paired\n"
      "# vs the three arm-3 seeds (arm 4 seed s - arm 3 seed s), into outputs/arm4_seeds.\n#\n"
      "#   sbatch arm4_compare.sbatch     (after both arm4_eval scripts end DONE)\n#\n"
    + COMMON.format(seg=SEG, job="arm4_cmp", awk_cond=names("arm4_ea", "arm4_eb", "arm4_cmp"),
                    conflicts="an arm-4 evaluation, or another copy")
    + body)
print("wrote", sorted(p.name for p in out_dir.glob("arm4_eval_*.sbatch")) + ["arm4_compare.sbatch"])
