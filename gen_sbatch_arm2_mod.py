"""Write the single-modality teacher SLURM scripts (DECISIONS.md D70-D71, ARM2_MOD_CODE_PLAN.md
§7) from ONE template, so the CT and MRI scripts can only differ where they must. Re-run this
rather than hand-editing the outputs:  python gen_sbatch_arm2_mod.py <dir>

  arm2_ct_train.sbatch    A100: train the CT-only r=4 teacher, then merge + merge check
  arm2_mri_train.sbatch   A100: the same for MRI-only
  arm2_ct_eval.sbatch     A40: verify the merged checkpoint -> eval_sam.py (unchanged) ->
                          aggregate -> compare vs arm 1b and vs the joint arm 2 (r4)
  arm2_mri_eval.sbatch    A40: the same for MRI-only

The arm-2 template (gen_sbatch.py, unchanged). Training and finalize take arm 2's exact
arguments plus --modality; there is one rank (4), so there is no selection script. In the
evaluation scripts a failing evaluation or aggregation stops the script; a failing comparison
is reported, the script carries on and ends with exit code 5.
"""
import sys
from pathlib import Path

out_dir = Path(sys.argv[1])
SEG = "/home/rethinkingai-self/vihaan/Segmentation"
BASE_CKPT = "sam_vit_b_01ec64.pth"
MODS = {"ct": "CT", "mri": "MRI"}
TRAIN_TIME = {"ct": "20:00:00", "mri": "10:00:00"}   # estimates 11.5 h / 5 h (D70); resumable
EVAL_TIME = "03:00:00"                                # as arm 2's evaluation
# arm 2's training arguments (gen_sbatch.TRAIN_ARGS with the preflight's batch 8 x accum 1)
TRAIN_ARGS = ('--processed "$SEG/data/processed" --checkpoint "$CKPT" --rank 4 --alpha 4 \\\n'
              '    --run-dir "$RUN" --merged-out "$MERGED" --epochs 35 --batch 8 --accum 1 \\\n'
              '    --lr-lora 5e-4 --lr-dec 1e-4 --seed 643 --workers 10 --expect-gpu A100 --modality {m}')
REFS = (("arm1_vit_b", "SAM ViT-B (arm 1b)"), ("arm2_r4", "Arm 2 r=4 (joint CT+MRI teacher)"))

HEADER = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH -N 1
#SBATCH --ntasks-per-node={ntasks}
#SBATCH --gres=gpu:1
#SBATCH --partition={part}
#SBATCH --qos={part}
#SBATCH --account=vihaan
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --output={seg}/outputs/{log}.%j.out
#SBATCH --error={seg}/outputs/{log}.%j.err
#
# GENERATED by gen_sbatch_arm2_mod.py -- edit the generator, not this file. (DECISIONS.md D71)
#
"""

COMMON = """set -u
export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE:-8}}
export MKL_NUM_THREADS=$OMP_NUM_THREADS OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS NUMEXPR_NUM_THREADS=$OMP_NUM_THREADS
SEG={seg}
PY=/home/rethinkingai-self/vihaan/miniconda3/envs/seg311/bin/python
{vars}
echo "=== job ${{SLURM_JOB_ID:-manual}} ({job}) on $(hostname)"
[ -x "$PY" ] || {{ echo "python not found: $PY"; exit 2; }}

# Refuse to run next to any other job that writes the same files: {conflicts}.
if command -v squeue >/dev/null 2>&1; then
    OTHERS=$(squeue --me -h -o "%i %j %T" 2>/dev/null |
             awk -v me="${{SLURM_JOB_ID:-none}}" '$1 != me && ({awk_cond})')
    if [ -n "$OTHERS" ]; then
        echo "REFUSING TO START -- these jobs write the same files:"
        echo "$OTHERS"
        echo "wait for them to finish, or scancel them, then resubmit"
        exit 3
    fi
else
    echo "warning: squeue unavailable on this node; overlap check skipped"
fi

nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
GPU=$(nvidia-smi --query-gpu=name --format=csv,noheader | head -n 1)
case "$GPU" in
    *{gpu}*) ;;
    *) echo "REFUSING TO START -- this job must run on an {gpu}, got '$GPU'"; exit 4 ;;
esac
# Prerequisites, checked only after the overlap and GPU guards (they may run python).
{file_checks}"$PY" -c "import torch,surface_distance,numpy,segment_anything;print('torch',torch.__version__,'cuda',torch.cuda.is_available(),'numpy',numpy.__version__)"
echo
"""

DGX = {"part": "dgx", "ntasks": 16, "mem": "128G", "gpu": "A100"}
A40_EVAL = {"part": "a40", "ntasks": 8, "mem": "96G", "gpu": "A40"}


def names(*jobs: str) -> str:
    return " || ".join(f'$2 == "{j}"' for j in jobs)


def write(name, job, time_, hw, doc, vars_, checks, cond_jobs, conflicts, body):
    (out_dir / name).write_text(
        HEADER.format(job=job, ntasks=hw["ntasks"], part=hw["part"], mem=hw["mem"], time=time_,
                      seg=SEG, log=name[:-len(".sbatch")])
        + doc
        + COMMON.format(seg=SEG, job=job, vars=vars_, file_checks=checks, awk_cond=names(*cond_jobs),
                        conflicts=conflicts, gpu=hw["gpu"])
        + body)


def compare(m: str, M: str, ref: str, ref_label: str) -> str:
    a = f"$SEG/outputs/{ref}"
    return (f'echo; echo "=== compare with {ref_label} ({a})"\n'
            f'if [ -f "{a}/run.json" ]; then\n'
            f'    "$PY" "$SEG/scripts/compare_arms.py" --a "{a}" --b "$OUT" \\\n'
            f'        --label-a "{ref_label}" --label-b "Arm 2 {M}-only r=4"\n'
            f'    C=$?; echo "=== compare vs {ref} exit $C"; [ "$C" -ne 0 ] && CMP_FAIL=1\n'
            f'else\n'
            f'    echo "=== compare vs {ref} skipped: {a}/run.json not found"; CMP_FAIL=1\n'
            f'fi\n')


for m, M in MODS.items():
    run_vars = (f'CKPT=$SEG/checkpoints/{BASE_CKPT}\nRUN=$SEG/runs/arm2_{m}_r4\n'
                f'MERGED=$SEG/checkpoints/sam_vit_b_arm2_{m}_r4.pth\n')
    args = TRAIN_ARGS.format(m=m)
    write(f"arm2_{m}_train.sbatch", f"a2{m}_tr", TRAIN_TIME[m], DGX,
          f"# Single-modality teacher TRAINING, {M} only (DECISIONS.md D70-D71): SAM ViT-B + LoRA r=4\n"
          f"# (alpha 4, q/v of all 12 blocks) + the full mask decoder, on an A100. Arm 2's recipe on\n"
          f"# AMOS train {M} slices only, uniform draws, best epoch by AMOS val {M} Dice @ 10% jitter.\n#\n"
          f"#   sbatch arm2_{m}_train.sbatch\n#\n"
          f"# Resumable (resubmit the same script after a timeout; a finished run exits TRAIN_OK at\n"
          f"# once). Then merges the best epoch's LoRA into a plain ViT-B checkpoint and checks the\n"
          f"# merge (FINALIZE_OK). The CT and MRI scripts differ ONLY in the modality and time limit.\n",
          run_vars, f'[ -f "$CKPT" ] || {{ echo "checkpoint not found: $CKPT"; exit 2; }}\n',
          (f"a2{m}_tr", f"a2{m}_ev"), f"another copy of this training job, or the {M}-only evaluation",
          f'"$PY" "$SEG/scripts/train_sam_lora.py" {args}\n'
          'RC=$?\necho "=== train exit $RC"\n[ "$RC" -ne 0 ] && exit "$RC"\n\n'
          'echo; echo "=== finalize (merge + merge check)"\n'
          f'"$PY" "$SEG/scripts/train_sam_lora.py" {args} --finalize\n'
          'FRC=$?\necho "=== finalize exit $FRC"\nexit "$FRC"\n')

    body = ('"$PY" "$SEG/scripts/eval_sam.py" \\\n    --processed "$SEG/data/processed" \\\n'
            '    --checkpoint "$MERGED" \\\n    --model-type vit_b \\\n    --out "$OUT" \\\n    --resume\n'
            'RC=$?\necho "=== eval exit $RC"\n'
            '[ "$RC" -ne 0 ] && { echo "STOPPING -- evaluation failed"; exit "$RC"; }\n\n'
            'echo; echo "=== aggregate"\n'
            '"$PY" "$SEG/scripts/aggregate_arm.py" --arm-dir "$OUT" \\\n'
            f'    --label "Arm 2 {M}-only (r=4): SAM ViT-B fine-tuned on AMOS {M} only (LoRA q,v r=4 + decoder)"\n'
            'RC=$?\necho "=== aggregate exit $RC"\n'
            '[ "$RC" -ne 0 ] && { echo "STOPPING -- aggregation failed"; exit "$RC"; }\n'
            'CMP_FAIL=0\n'
            + "".join(compare(m, M, ref, lab) for ref, lab in REFS)
            + 'echo\nif [ "$CMP_FAIL" -ne 0 ]; then echo "=== DONE, but a comparison FAILED (see above)"; exit 5; fi\n'
              'echo "=== DONE: evaluated, aggregated and compared"\nexit 0\n')
    write(f"arm2_{m}_eval.sbatch", f"a2{m}_ev", EVAL_TIME, A40_EVAL,
          f"# Single-modality teacher EVALUATION, {M} only (DECISIONS.md D70-D71), on an A40 exactly like\n"
          f"# arms 1b and 2.\n#\n"
          f"#   sbatch arm2_{m}_eval.sbatch       (after arm2_{m}_train.sbatch ends FINALIZE_OK)\n#\n"
          f"# Unchanged eval_sam.py on the merged {M}-only checkpoint, all 13,145 test instances (both\n"
          f"# modalities: same-modality and cross-modality groups alike) -> outputs/arm2_{m}_r4, then\n"
          f"# aggregation, then paired comparisons with arm 1b and with the joint arm 2 (r4).\n"
          f"# Always resumes: resubmit the same script after a timeout.\n",
          run_vars + f"OUT=$SEG/outputs/arm2_{m}_r4\n",
          f'"$PY" "$SEG/scripts/train_sam_lora.py" --processed "$SEG/data/processed" --checkpoint "$CKPT" \\\n'
          f'    --rank 4 --run-dir "$RUN" --merged-out "$MERGED" --modality {m} --check-merged '
          '|| { echo "REFUSING TO START -- merged checkpoint not verified"; exit 6; }\n',
          (f"a2{m}_tr", f"a2{m}_ev"), f"the {M}-only training job, or another copy of this evaluation",
          body)

print("wrote", sorted(f"arm2_{m}_{k}.sbatch" for m in MODS for k in ("train", "eval")))
